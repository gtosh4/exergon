#!/usr/bin/env python3
"""Regenerate the docs index files from note frontmatter.

The catalog portions of docs/README.md, docs/technical/README.md,
docs/market/README.md and docs/design-decisions.md are derived from each
note's YAML frontmatter (type/title/summary/tags/status). Hand-written
analysis in those files is preserved — only the catalog region is replaced.

Run after adding, removing, or re-describing a doc:  python3 scripts/gen_docs_index.py
"""
import os, re, sys

DOCS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs")
GEN = "<!-- generated by scripts/gen_docs_index.py from note frontmatter — do not hand-edit this catalog; re-run the script instead -->"

FM = re.compile(r'^---\n(.*?)\n---\n', re.S)

def load(rel):
    with open(os.path.join(DOCS, rel), encoding="utf-8") as fh:
        src = fh.read()
    m = FM.match(src)
    fm = m.group(1) if m else ""
    def field(k):
        mm = re.search(rf'^{k}:\s*(.*)$', fm, re.M)
        return mm.group(1).strip() if mm else None
    def strv(k):
        v = field(k)
        return v.strip().strip('"') if v else None
    d = {"rel": rel, "type": strv("type"), "title": strv("title") or os.path.basename(rel),
         "summary": strv("summary") or "", "status": strv("status"), "date": strv("date"),
         "tags": []}
    tv = field("tags")
    if tv:
        d["tags"] = [t.strip().strip('"') for t in tv.strip("[]").split(",") if t.strip()]
    return d

def all_notes():
    out = []
    for root, dirs, fs in os.walk(DOCS):
        dirs[:] = [x for x in dirs if x != ".obsidian"]
        for f in fs:
            if f.endswith(".md"):
                out.append(load(os.path.relpath(os.path.join(root, f), DOCS)))
    return out

def noext(rel):
    return os.path.splitext(rel)[0]

def linktarget(rel):
    # basename wikilinks resolve in markdown-oxide (LSP); keep the full path only for
    # README (its basename collides 3×). Catalog/decision targets are otherwise unique.
    b = os.path.basename(noext(rel))
    return noext(rel) if b == "README" else b

def line(d):
    s = f" _(status: {d['status']})_" if d.get("status") else ""
    tags = "  ·  " + " ".join(f"#{t}" for t in d["tags"]) if d["tags"] else ""
    return f"- [[{linktarget(d['rel'])}|{d['title']}]] — {d['summary']}{s}{tags}"

def replace_region(src, start_h, end_h, new_block):
    si = src.index(start_h)
    ei = src.index(end_h, si)
    return src[:si] + new_block.rstrip() + "\n\n" + src[ei:]

def build_root(notes):
    docs = sorted([n for n in notes if n["type"] == "design" and "/" not in n["rel"]
                   and n["rel"] not in ("README.md", "design-decisions.md")],
                  key=lambda d: d["title"].lower())
    body = ["## Documents", "", GEN, ""]
    body += [line(d) for d in docs]
    body += ["", "**Sub-indexes:**", "",
             "- [[technical/README|Technical design specs]] — ECS components, systems, events, and edge cases per system.",
             "- [[market/README|Market research]] — competitor/adjacent titles, product lessons, positioning.",
             "- [[design-decisions|Design decisions log]] — atomic decision notes with rationale, newest first.", ""]
    return "\n".join(body)

def build_folder(notes, folder, heading):
    docs = sorted([n for n in notes if n["type"] == ({"technical": "technical", "market": "market"}[folder])
                   and os.path.basename(n["rel"]) != "README.md"],
                  key=lambda d: d["title"].lower())
    body = [heading, "", GEN, ""] + [line(d) for d in docs] + [""]
    return "\n".join(body)

def build_decisions(notes):
    decs = sorted([n for n in notes if n["type"] == "decision"],
                  key=lambda d: (d.get("date") or ""), reverse=True)
    body = [GEN, ""]
    for d in decs:
        tags = " ".join(f"#{t}" for t in d["tags"])
        body.append(f"- **{d['date']}** — [[{linktarget(d['rel'])}|{d['title']}]]  ·  {tags}")
    body.append("")
    return "\n".join(body)

def write(rel, content):
    p = os.path.join(DOCS, rel)
    with open(p, "w", encoding="utf-8") as fh:
        fh.write(content)

def main():
    dry = "--write" not in sys.argv
    notes = all_notes()

    # --- three READMEs: region replacement, preserve curated prose ---
    jobs = [
        ("README.md", "## Documents", "## How to keep docs current", lambda: build_root(notes)),
        ("technical/README.md", "## Designs", "## TODO", lambda: build_folder(notes, "technical", "## Designs")),
        ("market/README.md", "## Reference Notes", "## Core Market Position", lambda: build_folder(notes, "market", "## Reference Notes")),
    ]
    for rel, sh, eh, builder in jobs:
        with open(os.path.join(DOCS, rel), encoding="utf-8") as fh:
            src = fh.read()
        out = replace_region(src, sh, eh, builder())
        if dry:
            print(f"[dry] {rel}: {'changed' if out != src else 'unchanged'}")
        else:
            write(rel, out)

    # --- design-decisions.md: rebuild body (content lives in decisions/) ---
    dd = load("design-decisions.md")
    fm_block = FM.match(open(os.path.join(DOCS, "design-decisions.md"), encoding="utf-8").read()).group(0)
    intro = ("# Design Decisions Log\n\n"
             "Rationale and context behind key decisions. The GDD holds the *what*; these notes capture the *why* "
             "and record alternatives considered. Each decision is an atomic note in `decisions/`; this page indexes "
             "them newest-first. To add one, drop a note in `decisions/` (frontmatter `type: decision`, `date`, `title`, "
             "`summary`, `tags`) and re-run `scripts/gen_docs_index.py`.\n\n")
    out = fm_block + "\n" + intro + build_decisions(notes)
    if dry:
        print("[dry] design-decisions.md rebuilt")
    else:
        write("design-decisions.md", out)

    print(f"{'DRY-RUN (pass --write)' if dry else 'WROTE indexes'}: {len(notes)} notes")

if __name__ == "__main__":
    main()
